"""Render the two 票根 illustrations from the icon's stub geometry.

  pair  two stubs, the mark freed from its plate: capture and connect moments
  box   票盒, stubs filed upright with the newest pulled up: genuine empty states

Outputs (paths relative to the repository root):
  backend/app/templates/web/partials/brand_art.html   inline SVG macros, coloured by --art-* tokens
  android/app/src/main/res/drawable/art_stub_{pair,box}_{paper,midnight}.xml

  python docs/design_reference/brand-icon/render_art.py
"""
from __future__ import annotations

from render_icons import ROOT, Stub, circle, num, vd_colour

STUB = Stub(w=46, h=80, r=6, cut=17, notch=7.5)
HOLES = "".join(circle(-STUB.w / 2 + STUB.notch + (STUB.w - 2 * STUB.notch) / 5 * (i + 1), STUB.cut - 4, 1.9)
                for i in range(4))

# Mirrors the --art-* tokens in backend/app/static/shared/tokens.css.
PALETTE = {
    "paper": {"paper": "#FBF6EA", "edge": "#DED4BF", "leaf": "#2B6E5C", "sage": "#A9C9BC", "coral": "#E0583B",
              "shadow": "#0D3D38", "shadow_alpha": 0.10, "tray": "#DCE7E0", "lip": "#C4D6CC"},
    "midnight": {"paper": "#EFE8D8", "edge": "#EFE8D8", "leaf": "#3F8C75", "sage": "#5E8576", "coral": "#EE6A4D",
                 "shadow": "#000000", "shadow_alpha": 0.35, "tray": "#25302B", "lip": "#2F3C36"},
}


def rrect(x: float, y: float, w: float, h: float, r: float) -> str:
    return (f"M{num(x + r)},{num(y)}H{num(x + w - r)}A{num(r)},{num(r)} 0 0,1 {num(x + w)},{num(y + r)}"
            f"V{num(y + h - r)}A{num(r)},{num(r)} 0 0,1 {num(x + w - r)},{num(y + h)}H{num(x + r)}"
            f"A{num(r)},{num(r)} 0 0,1 {num(x)},{num(y + h - r)}V{num(y + r)}A{num(r)},{num(r)} 0 0,1 {num(x + r)},{num(y)}Z")


def ellipse(cx: float, cy: float, rx: float, ry: float) -> str:
    return (f"M{num(cx - rx)},{num(cy)}A{num(rx)},{num(ry)} 0 1,0 {num(cx + rx)},{num(cy)}"
            f"A{num(rx)},{num(ry)} 0 1,0 {num(cx - rx)},{num(cy)}Z")


# A layer is (role, path, transform); transform is (tx, ty, rotation, scale) or None.
def stub_layers(kind: str, tx: float, ty: float, rot: float, scale: float = 1) -> list[tuple]:
    t = (tx, ty, rot, scale)
    if kind == "front":
        return [("paper", STUB.silhouette() + HOLES, t), ("coral", STUB.tail(), t)]
    return [(kind, STUB.silhouette(), t)]


ART = {
    "pair": {
        "view": (160, 140),
        "layers": [("shadow", ellipse(80, 130, 40, 5.5), None),
                   *stub_layers("leaf", 96, 62, 16), *stub_layers("front", 72, 74, -9)],
    },
    "box": {
        "view": (180, 130),
        "layers": [("shadow", ellipse(90, 126, 68, 5), None),
                   ("tray", rrect(30, 58, 120, 64, 10), None),
                   *stub_layers("sage", 58, 80, -6, 0.92), *stub_layers("leaf", 124, 78, 7, 0.92),
                   *stub_layers("front", 90, 46, -3),
                   ("lip", rrect(24, 90, 132, 34, 9), None),
                   ("tray", rrect(78, 100, 24, 9, 2.5), None)],
    },
}


def svg_transform(t: tuple | None) -> str:
    if t is None:
        return ""
    tx, ty, rot, scale = t
    return f' transform="translate({num(tx)} {num(ty)}) rotate({num(rot)}) scale({num(scale)})"'


def jinja_partial() -> str:
    out = ["{# Generated by docs/design_reference/brand-icon/render_art.py; edit the generator, not this file.",
           "   Decorative 票根 art: colours come from --art-* tokens (components.css), so both themes follow. #}"]
    for name, art in ART.items():
        w, h = art["view"]
        paths = []
        for role, d, t in art["layers"]:
            evenodd = ' fill-rule="evenodd"' if role == "paper" else ""
            paths.append(f'<path class="art-{role}" d="{d}"{evenodd}{svg_transform(t)}/>')
        out.append(f'{{% macro stub_{name}(extra_class="") -%}}\n'
                   f'<svg class="brand-art brand-art--{name} {{{{ extra_class }}}}" viewBox="0 0 {w} {h}" '
                   f'width="{w}" height="{h}" aria-hidden="true" focusable="false">'
                   + "".join(paths) + "</svg>\n{%- endmacro %}")
    return "\n".join(out) + "\n"


def vector(name: str, skin: str) -> str:
    art, colours = ART[name], PALETTE[skin]
    w, h = art["view"]
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<!-- 票根 {name} art, {skin}. Generated by docs/design_reference/brand-icon/render_art.py;",
             "     edit the generator, not this file. -->",
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             f'    android:width="{w}dp"', f'    android:height="{h}dp"',
             f'    android:viewportWidth="{w}"', f'    android:viewportHeight="{h}">']
    for role, d, t in art["layers"]:
        attrs = [f'android:fillColor="{vd_colour(colours[role])}"']
        if role == "shadow":
            attrs.append(f'android:fillAlpha="{num(colours["shadow_alpha"])}"')
        if role == "paper":
            attrs.append('android:fillType="evenOdd"')
            if colours["edge"] != colours["paper"]:
                attrs += [f'android:strokeColor="{vd_colour(colours["edge"])}"', 'android:strokeWidth="1.2"']
        path = "<path\n" + "".join(f"            {a}\n" for a in attrs) + f'            android:pathData="{d}" />'
        if t is None:
            lines.append("    " + path.replace("\n            ", "\n        "))
        else:
            tx, ty, rot, scale = t
            group = [f'android:translateX="{num(tx)}"', f'android:translateY="{num(ty)}"']
            if rot:
                group.append(f'android:rotation="{num(rot)}"')
            if scale != 1:
                group += [f'android:scaleX="{num(scale)}"', f'android:scaleY="{num(scale)}"']
            lines.append("    <group\n" + "".join(f"        {a}\n" for a in group[:-1]) + f"        {group[-1]}>")
            lines.append("        " + path)
            lines.append("    </group>")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main() -> None:
    (ROOT / "backend/app/templates/web/partials/brand_art.html").write_text(jinja_partial(), encoding="utf-8")
    res = ROOT / "android/app/src/main/res/drawable"
    for name in ART:
        for skin in PALETTE:
            (res / f"art_stub_{name}_{skin}.xml").write_text(vector(name, skin), encoding="utf-8")


if __name__ == "__main__":
    main()
