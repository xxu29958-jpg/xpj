@pytest.mark.parametrize(
    "mode",
    ["wrong_predicate", "not_valid", "no_inherit"],
)
def test_same_name_wrong_or_unvalidated_check_is_refused(mode: str) -> None:
    reset_schema()
    run_alembic(command.upgrade, "head")
    name = "ck_expenses_amount_cents_money_bounds"
    with engine.begin() as connection:
        connection.execute(text(f"ALTER TABLE expenses DROP CONSTRAINT {name}"))
        if mode == "wrong_predicate":
            predicate = "amount_cents IS NULL OR amount_cents >= 0"
            suffix = ""
        else:
            predicate = "amount_cents IS NULL OR (amount_cents BETWEEN 0 AND 9000000000000)"
            suffix = " NOT VALID" if mode == "not_valid" else " NO INHERIT"
        connection.execute(text(f"ALTER TABLE expenses ADD CONSTRAINT {name} CHECK ({predicate}){suffix}"))
    with pytest.raises(RuntimeError, match="constraint mismatch"):
        invoke_migration(load_migration())


