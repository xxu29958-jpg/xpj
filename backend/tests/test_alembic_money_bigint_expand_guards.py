def test_widen_emits_no_empty_alter_for_rate_only_tables(
    monkeypatch,
) -> None:
    reset_schema()
    run_alembic(command.upgrade, PREVIOUS_REVISION)
    module = load_migration()
    statements: list[str] = []
    monkeypatch.setattr(
        module.op,
        "execute",
        lambda statement: statements.append(str(statement)),
    )

    with engine.connect() as connection:
        module._widen(connection)

    expected_tables = {row[0] for row in module._MANIFEST}
    assert len(statements) == len(expected_tables)
    assert all(" TYPE bigint" in statement for statement in statements)
    assert all(
        "exchange_rates" not in statement and "fx_rates" not in statement
        for statement in statements
    )


def test_table_lock_barrier_rolls_back_before_any_rewrite() -> None:
    reset_schema()
    run_alembic(command.upgrade, PREVIOUS_REVISION)
    first = "bill_split_invitations"
    before = relfilenode(first)
    with engine.connect() as blocker:
        blocker.execute(text("LOCK TABLE repayments IN ROW EXCLUSIVE MODE"))
        started = time.perf_counter()
        with pytest.raises(OperationalError):
            run_alembic(command.upgrade, "head")
        elapsed = time.perf_counter() - started
        blocker.rollback()
    assert elapsed < 30
    assert current_revision() == PREVIOUS_REVISION
    assert column_type(first, "amount_cents") in {"integer", "int4"}
    assert relfilenode(first) == before


