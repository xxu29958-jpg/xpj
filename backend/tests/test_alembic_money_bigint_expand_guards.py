def _mutate_money_storage(connection, storage_kind: str) -> None:
    if storage_kind == "domain":
        connection.execute(
            text("CREATE DOMAIN c07_money_domain AS bigint")
        )
        connection.execute(
            text(
                "ALTER TABLE expenses ALTER COLUMN amount_cents "
                "TYPE c07_money_domain "
                "USING amount_cents::bigint::c07_money_domain"
            )
        )
    elif storage_kind == "identity":
        connection.execute(
            text(
                "ALTER TABLE budget_categories "
                "ALTER COLUMN amount_cents "
                "ADD GENERATED BY DEFAULT AS IDENTITY"
            )
        )
    else:
        connection.execute(
            text(
                "ALTER TABLE expense_items "
                "DROP COLUMN unit_price_cents"
            )
        )
        connection.execute(
            text(
                "ALTER TABLE expense_items "
                "ADD COLUMN unit_price_cents bigint "
                "GENERATED ALWAYS AS (0::bigint) STORED"
            )
        )


def test_final_shape_violation_blocks_without_partial_ddl() -> None:
    reset_schema()
    run_alembic(command.upgrade, PREVIOUS_REVISION)
    seed_owner()
    with SessionLocal() as db:
        db.add(
            RecurringItem(
                tenant_id="owner",
                merchant_key="legacy-zero",
                merchant_name="legacy-zero",
                baseline_amount_cents=0,
                last_amount_cents=0,
            )
        )
        db.commit()
    before = relfilenode("bill_split_invitations")
    with pytest.raises(Exception, match="target shape"):
        run_alembic(command.upgrade, "head")
    assert current_revision() == PREVIOUS_REVISION
    assert column_type("expenses", "amount_cents") in {"integer", "int4"}
    assert relfilenode("bill_split_invitations") == before


